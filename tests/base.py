    def run_and_verify_check_mode(self, conn_id):
        """Override: SAP SF discovers a dynamic set of OData entity sets.

        The base implementation asserts *exact* equality between
        ``expected_stream_names()`` and the discovered catalog names.
        That check would fail here because:
          1. Discovery returns ~400+ entity sets depending on tenant
             configuration, while ``expected_metadata`` tracks a curated
             subset.
          2. Some entries in ``expected_metadata`` are probed and omitted
             from the catalog when the API returns 4xx/5xx for them.

        This override relaxes the check to: every stream in
        ``expected_stream_names()`` that is *not* in ``streams_to_exclude()``
        must be present in the catalog.
        """
        check_job_name = runner.run_check_mode(self, conn_id)
        exit_status = menagerie.get_exit_status(conn_id, check_job_name)
        menagerie.verify_check_exit_status(self, exit_status, check_job_name)

        found_catalogs = menagerie.get_catalogs(conn_id)
        self.assertGreater(
            len(found_catalogs), 0,
            logging="A catalog was produced by discovery.",
        )

        found_names = {c["stream_name"] for c in found_catalogs}
        # Only require streams that we actually intend to test
        required = self.expected_stream_names() - self.streams_to_exclude()
        missing = required - found_names
        self.assertFalse(
            missing,
            msg=(
                f"Testable streams missing from catalog: {missing}. "
                f"Add them to streams_to_exclude() if they are inaccessible "
                f"in this environment."
            ),
        )
        return found_catalogs

